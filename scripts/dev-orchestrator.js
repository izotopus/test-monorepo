const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');
const { execSync, spawn } = require('child_process');

const PORTAL_PUBLIC_PATH = path.join(__dirname, '../apps/test-portal/dist/modules');
const appsToDev = ['test-portal', '@apps/test-dashboard']; // Dashboard zawsze w dev
// const appsToDev = ['@apps/dashboard']; // Zawsze dashboard/portal

function copyDirRecursive(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  const entries = fs.readdirSync(src, { withFileTypes: true });

  for (let entry of entries) {
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDirRecursive(srcPath, destPath);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

function run() {
  const rootDir = process.cwd();
  const configPath = path.resolve(rootDir, 'dev-config.yaml');
  
  if (!fs.existsSync(configPath)) {
    console.error(`❌ Config not found at ${configPath}`);
    process.exit(1);
  }

  const config = yaml.load(fs.readFileSync(configPath, 'utf8'));
  const appsConfig = config.apps;

  const mfSettingsForTS = {};
  const appsToBuild = [];
  const appsToDev = ['test-portal', '@apps/test-dashboard'];

  // --- ANALIZA YAML I PRZYGOTOWANIE KONFIGURACJI ---
  for (const [key, details] of Object.entries(appsConfig)) {
    const isDevMode = details.type === 'dev';
    
    // Decydujemy o URL na etapie generowania pliku
    let finalUrl = isDevMode ? details.devUrl : details.prodUrl;

    // Jeśli to build statyczny, musimy celować w port Portalu (Astro)
    if (!isDevMode && finalUrl.startsWith('/')) {
      finalUrl = `http://localhost:4321${finalUrl}`;
    }

    // Obiekt, który trafi do pliku .ts
    mfSettingsForTS[key] = {
      url: finalUrl,
      type: details.mfType,
      name: details.name,
      mode: details.type
    };

    if (isDevMode) {
      if (!appsToDev.includes(details.name)) appsToDev.push(details.name);
    } else {
      appsToBuild.push({ key, ...details });
    }
  }

  // --- KROK 1: GENEROWANIE PLIKU TYPESCRIPT ---
  console.log(`\n📝 Step 1: Generating TS config for @packages/logic...`);
  const outputPath = path.resolve(rootDir, 'packages/logic/src/microfrontends/generated-config.ts');
  
  const tsContent = `// AUTO-GENERATED by dev-orchestrator.js - DO NOT EDIT
export const MF_CONFIG = ${JSON.stringify(mfSettingsForTS, null, 2)} as const;
export type MFKey = keyof typeof MF_CONFIG;
`;

  // Upewnij się, że katalog istnieje przed zapisem
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, tsContent);
  console.log(`  ✅ Generated: ${outputPath}`);

  // --- KROK 2: BUILD MODUŁÓW STATYCZNYCH ---
  if (appsToBuild.length > 0) {
    console.log(`\n📦 Step 2: Building static modules via Turbo...`);
    const buildFilter = appsToBuild.map(a => `--filter=${a.name}`).join(' ');
    
    try {
      execSync(`pnpm turbo build ${buildFilter}`, { stdio: 'inherit' });
    } catch (e) {
      console.warn("⚠️ Some builds failed, but trying to collect what's available...");
    }

    // --- KROK 3: KOPIOWANIE DO PUBLIC PORTALU ---
    console.log(`\n📂 Step 3: Collecting dist files to Portal public folder...`);
    const portalPublicModules = path.resolve(rootDir, 'apps/test-portal/public/modules');

    for (const app of appsToBuild) {
      const sourceDir = path.resolve(rootDir, app.distDir);
      const folderName = app.key.toLowerCase().replace('_', '-');
      const destDir = path.resolve(portalPublicModules, folderName);

      if (fs.existsSync(sourceDir)) {
        if (fs.existsSync(destDir)) fs.rmSync(destDir, { recursive: true, force: true });
        copyDirRecursive(sourceDir, destDir);
        console.log(`  ✅ ${app.key} -> ${folderName}`);
      } else {
        console.error(`  ❌ Source not found for ${app.key} at ${sourceDir}`);
      }
    }
  }

  // --- KROK 4: URUCHOMIENIE SERWERÓW DEV ---
  console.log(`\n🚀 Step 4: Starting Dev Servers for: ${appsToDev.join(', ')}...`);
  
  const filters = appsToDev.map(n => `--filter=${n}`).join(' ');
  const fullCommand = `pnpm turbo dev ${filters}`;

  const child = spawn(fullCommand, {
    stdio: 'inherit',
    shell: true,
    cwd: rootDir
  });

  child.on('exit', (code) => {
    process.exit(code || 0);
  });
}

run();