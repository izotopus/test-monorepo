const { execSync, spawn } = require('child_process');
const path = require('path');
const fs = require('fs');
const utils = require('./lib/utils');

const MF_DEST_PATH = 'packages/logic/src/microfrontends';
const CONFIG_FILES = {
  DEV: 'generated-config.dev.ts',
  PROD: 'generated-config.prod.ts'
};

function run() {
  const isProdBuild = process.argv.includes('--prod');
  const baseUrl = process.env.BASE_URL || '/';
  const config = utils.loadConfig();
  
  const portalEntry = config.apps.TEST_PORTAL;
  if (!portalEntry) {
    console.error("❌ TEST_PORTAL not found in dev-config.yaml! Ensure it's defined.");
    process.exit(1);
  }

  const PORTAL_HOST = portalEntry.devUrl.replace(/\/$/, '');

  const outputDir = path.resolve(utils.rootDir, MF_DEST_PATH);
  utils.ensureStubsExist(outputDir, CONFIG_FILES);

  const mfSettingsForTS = {};
  const appsToDev = [];
  const appsToBuild = [];

  for (const [key, details] of Object.entries(config.apps)) {
    const currentMode = isProdBuild ? 'build' : details.type;
    const isDev = currentMode === 'dev';

    let finalUrl = isDev ? details.devUrl : details.prodUrl;

    if (finalUrl.startsWith('/')) {
      if (isProdBuild) {
        finalUrl = (baseUrl + finalUrl).replace(/\/+/g, '/');
      } else {
        finalUrl = `${PORTAL_HOST}${finalUrl}`;
      }
    }

    mfSettingsForTS[key] = {
      url: finalUrl,
      type: details.mfType,
      name: details.name,
      mode: currentMode
    };

    if (isDev) {
      appsToDev.push(details.name);
    } else if (currentMode === 'build') {
      appsToBuild.push(details.name);
    }
  }

  const isLogsEnabled = process.env.VITE_ENABLE_LOGS === 'true';

  const fileName = isProdBuild ? CONFIG_FILES.PROD : CONFIG_FILES.DEV;
  fs.writeFileSync(path.join(outputDir, fileName), `
// AUTO-GENERATED by dev-orchestrator.js - DO NOT EDIT
export const GLOBAL_CONFIG: { ENABLE_LOGS: boolean } = {
  ENABLE_LOGS: ${isLogsEnabled}
} as const;
export const MF_CONFIG = ${JSON.stringify(mfSettingsForTS, null, 2)} as const;
export type MFKey = keyof typeof MF_CONFIG;`);

  if (appsToBuild.length > 0 && !isProdBuild) {
    console.log(`\n📦 Building & Collecting static modules for DEV...`);
    const filterStr = appsToBuild.map(n => `--filter=${n}`).join(' ');
    execSync(`pnpm turbo build ${filterStr}`, { stdio: 'inherit' });
    
    execSync(`node scripts/collect-modules.js`, { stdio: 'inherit' });
  }

  if (isProdBuild) return console.log('✅ Prod config generated.');
  
  if (appsToDev.length === 0) return console.log('\nℹ️ No apps marked as "dev". Nothing to start.');

  console.log(`\n🚀 Starting Dev Servers for: ${appsToDev.join(', ')}...`);
  
  const filters = appsToDev.map(n => `--filter=${n}`).join(' ');
  const fullCommand = `pnpm turbo dev ${filters}`;

  const child = spawn(fullCommand, {
    stdio: 'inherit',
    shell: true,
    cwd: utils.rootDir,
    env: { ...process.env },
  });

  child.on('exit', (code) => {
    process.exit(code || 0);
  });
}

run();